// Regenerates scripts/import/hevyOfficialNames.ts from openGym's Hevy map:
//   npx tsx scripts/build-hevy-names.ts ~/openGym/frontend/src/lib/hevy-id-map.js
//
// openGym's map lists Hevy's built-in exercise titles (lowercased) -> catalogue
// id, sometimes several titles per id and sometimes loosely. We keep a title
// only when its equipment suffix agrees with the catalogue entry, and pick the
// closest-worded one when several qualify.
import fs from 'node:fs';
import path from 'node:path';
import { toHevyName } from './import/catalogue';
import type { CatalogueEntry } from '@/types/import';

const words = (s: string) => new Set(s.toLowerCase().match(/[a-z0-9]+/g) ?? []);
const equipmentOf = (name: string) => name.match(/\(([^)]*)\)\s*$/)?.[1].toLowerCase() ?? '';

function similarity(a: string, b: string): number {
  const wa = words(a);
  const wb = words(b);
  const shared = [...wa].filter((w) => wb.has(w)).length;
  return shared / new Set([...wa, ...wb]).size;
}

// Hevy capitalises every word, including after "-", "(" and "/".
function hevyCase(title: string): string {
  return title.replace(/(^|[\s(\-/])([a-z])/g, (_, sep: string, ch: string) => sep + ch.toUpperCase());
}

function main() {
  const [mapPath] = process.argv.slice(2);
  if (!mapPath) {
    console.error('Usage: npx tsx scripts/build-hevy-names.ts <openGym hevy-id-map.js>');
    process.exit(1);
  }
  const root = path.join(__dirname, '..');
  const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'catalogue/exercises.json'), 'utf-8')) as CatalogueEntry[];
  const converted = new Map(catalogue.map((e) => [e.id, toHevyName(e.name)]));

  const titlesById = new Map<string, string[]>();
  for (const [, title, id] of fs.readFileSync(mapPath, 'utf-8').matchAll(/^\s*"([^"]+)":\s*"(\d{4,5})"/gm)) {
    if (!/[a-z]/.test(title) || !converted.has(id)) continue; // skip Hevy template ids
    titlesById.set(id, [...(titlesById.get(id) ?? []), hevyCase(title)]);
  }

  const lines: string[] = [];
  let rejected = 0;
  for (const id of [...titlesById.keys()].sort()) {
    const ours = converted.get(id)!;
    const candidates = titlesById.get(id)!.filter((t) => equipmentOf(t) === equipmentOf(ours));
    rejected += titlesById.get(id)!.length - candidates.length;
    if (candidates.length === 0) continue;
    const best = candidates.reduce((a, b) => (similarity(b, ours) > similarity(a, ours) ? b : a));
    const original = catalogue.find((e) => e.id === id)!.name;
    lines.push(`  '${id}': ${JSON.stringify(best)}, // ${original}`);
  }

  const out = `// AUTO-GENERATED by scripts/build-hevy-names.ts — do not edit by hand.
// openGym catalogue id -> Hevy's exact built-in exercise name (from openGym's
// Hevy map), kept only where the equipment agrees with the catalogue entry.
export const HEVY_OFFICIAL_NAMES: Record<string, string> = {
${lines.join('\n')}
};
`;
  fs.writeFileSync(path.join(root, 'scripts/import/hevyOfficialNames.ts'), out);
  console.log(`${lines.length} Hevy names written, ${rejected} titles rejected for equipment mismatch`);
}

main();
